/// `0D 92`: one member joining (the leader invited Cirilla).
#[test]
fn member_joining() {
    let body = hex(&[
    "03031d1e00006109490d2433303131423739462d343430442d343432362d383239452d313138453343304343433039b8",
    "a504000000610907436972696c6c611c000000d86ad86abf100000bf1000000000000000000000000000000000000014",
    "000000010000005a02000033752547f12b20c73aa2aa4607044354524c020000002d000000000000001b0600004c3f01",
    "0000000000",
    ]);
    let members = parse_party_roster_92(&body).expect("member");
    assert_eq!(members.len(), 1);
    assert_eq!((members[0].0.as_str(), members[0].1.level, members[0].1.server_id), ("Cirilla", 28, 2401));
}
